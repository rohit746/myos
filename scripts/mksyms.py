#!/usr/bin/env python3
"""Write the kernel's symbol table (backtrace.h) as an assembly file.

    scripts/mksyms.py <kernel.elf> <out.S>
    scripts/mksyms.py --empty <out.S>

Reads the function symbols in the ELF's .text (C functions, and the labels
of the assembly files) and writes them, sorted by address, into a .ksyms
section that the linker script puts at the end of .rodata:

    ksyms_count   the number of entries (8 bytes)
    ksyms_table   entries of {address, offset of the name} (8 bytes each)
    ksyms_names   the names, NUL-terminated

The Makefile links the kernel twice: first with an empty table (--empty),
then with the table of that first kernel. .text comes before .rodata, so the
table doesn't move any function, and its addresses stay right; the Makefile
checks that by writing the table of the second kernel too and comparing.
"""

import struct
import sys

SHT_SYMTAB = 2
STT_NOTYPE, STT_FUNC = 0, 2
STB_LOCAL = 0


def text_symbols(path):
    data = open(path, "rb").read()
    if data[:4] != b"\x7fELF" or data[4] != 2 or data[5] != 1:
        sys.exit(f"mksyms: {path} is not a little-endian ELF64 file")
    shoff, = struct.unpack_from("<Q", data, 0x28)
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", data, 0x3a)
    sections = [struct.unpack_from("<IIQQQQIIQQ", data, shoff + i * shentsize) for i in range(shnum)]

    def cstr(offset):
        return data[offset:data.index(b"\0", offset)].decode()

    shstr = sections[shstrndx][4]
    names = [cstr(shstr + s[0]) for s in sections]
    text = names.index(".text")
    symtab = next(s for s in sections if s[1] == SHT_SYMTAB)
    strtab = sections[symtab[6]][4]
    syms = {}
    for off in range(symtab[4], symtab[4] + symtab[5], symtab[9]):
        name, info, _, shndx, value, _ = struct.unpack_from("<IBBHQQ", data, off)
        kind, bind = info & 0xf, info >> 4
        name = cstr(strtab + name)
        if shndx != text or kind not in (STT_NOTYPE, STT_FUNC) or not name or name.startswith(".L"):
            continue
        # One name per address: a function over a plain label, a global
        # over a local, then the first in alphabetical order.
        rank = (kind != STT_FUNC, bind == STB_LOCAL, name)
        if value not in syms or rank < syms[value][0]:
            syms[value] = (rank, name)
    return sorted((addr, name) for addr, (_, name) in syms.items())


def write(path, syms):
    out = ['// Generated by scripts/mksyms.py: the kernel\'s symbol table (backtrace.h).',
           '.section .ksyms, "a", @progbits',
           '.balign 8',
           '.global ksyms_count, ksyms_table, ksyms_names',
           f'ksyms_count: .quad {len(syms)}',
           'ksyms_table:']
    offset = 0
    for addr, name in syms:
        out.append(f'    .quad 0x{addr:x}, {offset} // {name}')
        offset += len(name.encode()) + 1
    out.append('ksyms_names:')
    out += [f'    .asciz "{name}"' for _, name in syms]
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    write(sys.argv[2], [] if sys.argv[1] == "--empty" else text_symbols(sys.argv[1]))
